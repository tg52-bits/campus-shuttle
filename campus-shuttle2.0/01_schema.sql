-- =====================================================================
-- PART 3: simulator bookkeeping (needed before trips can reference a run)
-- =====================================================================
CREATE TABLE IF NOT EXISTS sim.run (
    run_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seed         bigint NOT NULL,
    parameters   jsonb  NOT NULL,
    description  text,
    started_at   timestamp NOT NULL DEFAULT now()
);

-- Events the simulator deliberately injected (ground truth for evaluation).
CREATE TABLE IF NOT EXISTS sim.injected_event (
    event_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        integer NOT NULL REFERENCES sim.run(run_id) ON DELETE CASCADE,
    event_type    varchar(30) NOT NULL
                  CHECK (event_type IN ('congestion','closure','breakdown','gps_dropout')),
    road_id       integer REFERENCES public.road_segments(road_id),
    valid_period  tsrange NOT NULL,
    magnitude     numeric,      -- e.g. speed factor 0.4 = 60% slower
    note          text
);


-- =====================================================================
-- PART 4: DYNAMIC data: plan, raw observations, derived observations
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.trips (
    trip_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id     integer REFERENCES public.timetable_departures(departure_id),
    service_date     date NOT NULL,
    route_id         integer NOT NULL REFERENCES public.routes(route_id),
    vehicle_id       integer NOT NULL REFERENCES public.vehicles(vehicle_id),
    driver_id        integer REFERENCES public.drivers(driver_id),
    scheduled_start  timestamp NOT NULL,
    scheduled_end    timestamp,     -- derived from the last stop's planned offset
    actual_start     timestamp,     -- derived from stop events
    actual_end       timestamp,     -- derived from stop events
    status           varchar(30) NOT NULL DEFAULT 'Scheduled'
                     CHECK (status IN ('Scheduled','In Progress','Completed','Cancelled')),
    sim_run_id       integer REFERENCES sim.run(run_id),
    data_source      public.data_source_t,
    -- generating the same timetable departure twice for one date is impossible
    CONSTRAINT uq_trips_departure_date UNIQUE (departure_id, service_date),
    CONSTRAINT chk_trips_scheduled CHECK (scheduled_end IS NULL OR scheduled_end >= scheduled_start),
    CONSTRAINT chk_trips_actual CHECK (actual_end IS NULL OR actual_start IS NULL OR actual_end >= actual_start),
    -- a vehicle (or driver) cannot be on two scheduled trips at the same time
    CONSTRAINT excl_trips_vehicle_overlap
        EXCLUDE USING gist (vehicle_id WITH =, tsrange(scheduled_start, scheduled_end) WITH &&)
        WHERE (status <> 'Cancelled' AND scheduled_end IS NOT NULL),
    CONSTRAINT excl_trips_driver_overlap
        EXCLUDE USING gist (driver_id WITH =, tsrange(scheduled_start, scheduled_end) WITH &&)
        WHERE (status <> 'Cancelled' AND scheduled_end IS NOT NULL AND driver_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.trip_stop_event (
    trip_stop_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id              integer NOT NULL REFERENCES public.trips(trip_id) ON DELETE CASCADE,
    stop_id              integer NOT NULL REFERENCES public.stops(stop_id),
    stop_sequence        integer NOT NULL CHECK (stop_sequence > 0),
    scheduled_arrival    timestamp,
    scheduled_departure  timestamp,
    actual_arrival       timestamp,     -- derived from GPS (or entered manually)
    actual_departure     timestamp,
    detection_method     varchar(20) CHECK (detection_method IS NULL OR detection_method IN ('gps_inferred','manual')),
    data_source          public.data_source_t,
    CONSTRAINT uq_trip_stop_event_trip_sequence UNIQUE (trip_id, stop_sequence),
    CONSTRAINT chk_tse_scheduled CHECK (scheduled_departure IS NULL OR scheduled_arrival IS NULL
                                        OR scheduled_departure >= scheduled_arrival),
    CONSTRAINT chk_tse_actual CHECK (actual_departure IS NULL OR actual_arrival IS NULL
                                     OR actual_departure >= actual_arrival)
);

-- THE raw operational stream. Everything else about a trip's progress is
-- derived from this table.
CREATE TABLE IF NOT EXISTS public.vehicle_position (
    position_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id   integer NOT NULL REFERENCES public.vehicles(vehicle_id),
    trip_id      integer REFERENCES public.trips(trip_id),   -- may be inferred after arrival
    recorded_at  timestamp NOT NULL,
    location     geometry(Point, 4326) NOT NULL,
    speed_kmh    numeric(6,2) CHECK (speed_kmh IS NULL OR speed_kmh >= 0),
    heading_deg  numeric(5,2) CHECK (heading_deg IS NULL OR (heading_deg >= 0 AND heading_deg < 360)),
    accuracy_m   numeric(6,2) CHECK (accuracy_m IS NULL OR accuracy_m >= 0),
    sim_run_id   integer REFERENCES sim.run(run_id),
    data_source  public.data_source_t,
    -- one fix per vehicle per instant; also makes loads rerunnable
    CONSTRAINT uq_vehicle_position_vehicle_time UNIQUE (vehicle_id, recorded_at),
    CONSTRAINT chk_vehicle_position_location_valid
        CHECK (ST_IsValid(location) AND NOT ST_IsEmpty(location)
               AND ST_X(location) BETWEEN -180 AND 180
               AND ST_Y(location) BETWEEN  -90 AND  90)
);

-- Derived: each fix matched to its trip's route (raw data stays untouched).
CREATE TABLE IF NOT EXISTS public.position_match (
    position_id      bigint PRIMARY KEY REFERENCES public.vehicle_position(position_id) ON DELETE CASCADE,
    trip_id          integer REFERENCES public.trips(trip_id) ON DELETE CASCADE,
    route_id         integer REFERENCES public.routes(route_id),
    road_id          integer REFERENCES public.road_segments(road_id),
    measure_m        numeric(10,2) CHECK (measure_m IS NULL OR measure_m >= 0),
    route_fraction   numeric(7,6)  CHECK (route_fraction IS NULL OR route_fraction BETWEEN 0 AND 1),
    dist_to_route_m  numeric(8,2)  CHECK (dist_to_route_m IS NULL OR dist_to_route_m >= 0),
    on_route         boolean NOT NULL,
    matched_at       timestamp NOT NULL DEFAULT now()
);

-- Derived: when a trip entered and left each road segment.
CREATE TABLE IF NOT EXISTS public.segment_traversal (
    traversal_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id        integer NOT NULL REFERENCES public.trips(trip_id) ON DELETE CASCADE,
    road_id        integer NOT NULL REFERENCES public.road_segments(road_id),
    entered_at     timestamp NOT NULL,
    exited_at      timestamp NOT NULL,
    travel_time_s  numeric GENERATED ALWAYS AS (EXTRACT(EPOCH FROM (exited_at - entered_at))) STORED,
    avg_speed_kmh  numeric(6,2) CHECK (avg_speed_kmh IS NULL OR avg_speed_kmh >= 0),
    CONSTRAINT chk_segment_traversal_time CHECK (exited_at >= entered_at),
    CONSTRAINT uq_segment_traversal UNIQUE (trip_id, road_id, entered_at)
);

-- Derived summary: typical speed per road, day type and 15-minute bucket.
CREATE TABLE IF NOT EXISTS public.segment_speed_profile (
    road_id        integer NOT NULL REFERENCES public.road_segments(road_id),
    day_type       varchar(10) NOT NULL CHECK (day_type IN ('weekday','saturday','sunday')),
    bucket_start   time NOT NULL,
    avg_speed_kmh  numeric(6,2) NOT NULL CHECK (avg_speed_kmh >= 0),
    n_obs          integer NOT NULL CHECK (n_obs > 0),
    updated_at     timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (road_id, day_type, bucket_start)
);

-- Explicit incidents only. Ordinary lateness is computed from trip_stop_event.
CREATE TABLE IF NOT EXISTS public.delays (
    delay_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id         integer NOT NULL REFERENCES public.trips(trip_id),
    stop_id         integer REFERENCES public.stops(stop_id),
    road_id         integer REFERENCES public.road_segments(road_id),
    occurred_at     timestamp NOT NULL,
    delay_minutes   integer NOT NULL CHECK (delay_minutes >= 0),
    delay_type      varchar(50),
    note            text,
    data_source     public.data_source_t
);

-- Simulator ground truth: what really happened (never read by triggers).
CREATE TABLE IF NOT EXISTS sim.true_stop_visit (
    run_id         integer NOT NULL REFERENCES sim.run(run_id) ON DELETE CASCADE,
    trip_id        integer NOT NULL,
    stop_sequence  integer NOT NULL,
    true_arrival   timestamp NOT NULL,
    true_departure timestamp NOT NULL,
    PRIMARY KEY (run_id, trip_id, stop_sequence),
    CHECK (true_departure >= true_arrival)
);


