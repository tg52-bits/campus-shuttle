
-- =====================================================================
-- campus_shuttle_v2_schema.sql
-- Campus Shuttle: Spatio-Temporal Mobility Database, schema v2 (fresh build)
--
-- Run in : pgAdmin 4 > Query Tool, connected to a NEW EMPTY database
--          (Windows PostgreSQL 17). See "Setup" below.
-- Nature : creates objects only. It inserts NO sample data (only the small
--          set of documented configuration parameters in service_params).
-- Rerun  : safe to rerun on the v2 database (IF NOT EXISTS everywhere).
-- Safety : refuses to run on the OLD v1 database (see the guard in PART 0).
--
-- Setup (keeps your old database as a backup):
--   1. pgAdmin: disconnect from the old DB, right-click it > Properties >
--      rename to  campus_shuttle_v1_backup   (or take a Backup first).
--   2. Right-click Databases > Create > Database...  name: campus_shuttle
--   3. Open Query Tool on the new database and run this file one PART at a
--      time (select the part, press F5).
--
-- Table roles (also queryable afterwards:  SELECT * FROM v_table_roles;)
--   STATIC-SPATIAL      campus_zones, road_segments, stops, routes
--   STATIC-STRUCTURE    route_stops
--   REFERENCE           drivers, vehicles
--   TEMPORAL-REFERENCE  timetable_departures, vehicle_status_history, road_closures
--   CONFIG              service_params
--   DYNAMIC-PLAN        trips, trip_stop_event (planned part generated, actual part derived)
--   DYNAMIC-RAW         vehicle_position   <- the only raw operational stream
--   DYNAMIC-DERIVED     position_match, segment_traversal, segment_speed_profile
--   INCIDENT            delays
--   STAGING / GROUND-TRUTH   stg.*, sim.*
-- =====================================================================


-- =====================================================================
-- PART 0: guard, extensions, schemas, provenance domain
-- =====================================================================
DO $$
BEGIN
    -- v1 had public.trips without service_date. Refuse to mix schemas.
    IF to_regclass('public.trips') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema = 'public' AND table_name = 'trips'
                         AND column_name = 'service_date') THEN
        RAISE EXCEPTION
          'Old (v1) schema detected in this database. Create a new empty database and run this script there.';
    END IF;
END $$;

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- needed for temporal exclusion constraints

CREATE SCHEMA IF NOT EXISTS stg;   -- staging area for imports
CREATE SCHEMA IF NOT EXISTS sim;   -- simulator runs and ground truth

-- Provenance label carried by every table that can mix real and synthetic rows.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
                   WHERE n.nspname = 'public' AND t.typname = 'data_source_t') THEN
        CREATE DOMAIN public.data_source_t AS text
            NOT NULL DEFAULT 'unspecified'
            CHECK (VALUE IN ('unspecified','real_observed','real_osm','real_published',
                             'derived','simulated','assumed'));
    END IF;
END $$;


-- =====================================================================
-- PART 1: STATIC spatial layer (the fixed map)
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.campus_zones (
    zone_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name    varchar(100) NOT NULL UNIQUE,
    zone_type    varchar(30)  NOT NULL DEFAULT 'other'
                 CHECK (zone_type IN ('academic','residential','sports','gate','service','forest','other')),
    boundary     geometry(MultiPolygon, 4326) NOT NULL,
    data_source  public.data_source_t,
    CONSTRAINT chk_campus_zones_boundary_valid
        CHECK (ST_IsValid(boundary) AND NOT ST_IsEmpty(boundary))
);

CREATE TABLE IF NOT EXISTS public.road_segments (
    road_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_way_id       bigint,
    road_name        varchar(150),
    highway_class    varchar(50),
    oneway           boolean NOT NULL DEFAULT false,
    speed_limit_kmh  numeric(5,1) CHECK (speed_limit_kmh IS NULL OR speed_limit_kmh > 0),
    geom             geometry(LineString, 4326) NOT NULL,
    length_m         numeric(10,2) GENERATED ALWAYS AS (ST_Length(geom::geography)) STORED,
    source_node      integer,     -- graph topology, filled when the network is noded
    target_node      integer,
    data_source      public.data_source_t DEFAULT 'real_osm',
    CONSTRAINT chk_road_segments_geom_valid
        CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom) AND ST_NPoints(geom) >= 2)
);

CREATE TABLE IF NOT EXISTS public.stops (
    stop_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_code         varchar(20) UNIQUE,
    stop_name         varchar(100) NOT NULL UNIQUE,
    location          geometry(Point, 4326) NOT NULL,           -- INPUT
    zone_id           integer REFERENCES public.campus_zones(zone_id),   -- derived
    road_id           integer REFERENCES public.road_segments(road_id),  -- derived
    snapped_location  geometry(Point, 4326),                    -- derived: location snapped onto the road
    snap_distance_m   numeric(8,2) CHECK (snap_distance_m IS NULL OR snap_distance_m >= 0), -- derived
    data_source       public.data_source_t,
    CONSTRAINT chk_stops_location_valid
        CHECK (ST_IsValid(location) AND NOT ST_IsEmpty(location)
               AND ST_X(location) BETWEEN -180 AND 180
               AND ST_Y(location) BETWEEN  -90 AND  90)
);

CREATE TABLE IF NOT EXISTS public.routes (
    route_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code      varchar(20)  NOT NULL UNIQUE,
    route_name      varchar(150) NOT NULL UNIQUE,
    route_geometry  geometry(LineString, 4326),                 -- derived from stops + road network
    length_m        numeric(10,2) GENERATED ALWAYS AS (
                        CASE WHEN route_geometry IS NULL THEN NULL
                             ELSE ST_Length(route_geometry::geography) END) STORED,
    data_source     public.data_source_t,
    CONSTRAINT chk_routes_geometry_valid
        CHECK (route_geometry IS NULL
               OR (ST_IsValid(route_geometry) AND NOT ST_IsEmpty(route_geometry)
                   AND ST_NPoints(route_geometry) >= 2))
);

-- Ordered stops of a route. A stop may appear twice (loop routes), so there is
-- deliberately no UNIQUE (route_id, stop_id); the sequence is unique instead.
CREATE TABLE IF NOT EXISTS public.route_stops (
    route_stop_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id                  integer NOT NULL REFERENCES public.routes(route_id) ON DELETE CASCADE,
    stop_id                   integer NOT NULL REFERENCES public.stops(stop_id),
    stop_sequence             integer NOT NULL CHECK (stop_sequence > 0),
    distance_from_start_m     numeric(10,2) CHECK (distance_from_start_m IS NULL OR distance_from_start_m >= 0), -- derived
    planned_arrival_offset_s  integer CHECK (planned_arrival_offset_s IS NULL OR planned_arrival_offset_s >= 0),
    planned_departure_offset_s integer CHECK (planned_departure_offset_s IS NULL OR planned_departure_offset_s >= 0),
    CONSTRAINT uq_route_stops_route_sequence UNIQUE (route_id, stop_sequence),
    CONSTRAINT chk_route_stops_offsets
        CHECK (planned_arrival_offset_s IS NULL OR planned_departure_offset_s IS NULL
               OR planned_departure_offset_s >= planned_arrival_offset_s)
);


-- =====================================================================
-- PART 2: REFERENCE and TEMPORAL-REFERENCE data
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.drivers (
    driver_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL,
    license_info  varchar(100)
);

CREATE TABLE IF NOT EXISTS public.vehicles (
    vehicle_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no  varchar(20) UNIQUE,
    vehicle_type     varchar(50) NOT NULL,
    capacity         integer NOT NULL CHECK (capacity > 0),
    status           varchar(30) NOT NULL DEFAULT 'Active'
                     CHECK (status IN ('Active','Not Active','Maintenance'))  -- current snapshot only
);

-- Status over time. The overlap constraint is a temporal integrity rule:
-- a vehicle cannot have two different statuses at the same instant.
CREATE TABLE IF NOT EXISTS public.vehicle_status_history (
    status_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    integer NOT NULL REFERENCES public.vehicles(vehicle_id),
    status        varchar(30) NOT NULL CHECK (status IN ('Active','Not Active','Maintenance')),
    valid_period  tsrange NOT NULL CHECK (NOT isempty(valid_period)),
    reason        text,
    data_source   public.data_source_t,
    CONSTRAINT excl_vehicle_status_overlap
        EXCLUDE USING gist (vehicle_id WITH =, valid_period WITH &&)
);

-- Planned departures, versioned by validity dates (timetables are revised).
-- Planned times at later stops come from route_stops offsets.
CREATE TABLE IF NOT EXISTS public.timetable_departures (
    departure_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        integer NOT NULL REFERENCES public.routes(route_id),
    day_type        varchar(10) NOT NULL CHECK (day_type IN ('weekday','saturday','sunday')),
    departure_time  time NOT NULL,
    valid_from      date NOT NULL,
    valid_to        date,
    source_doc      text,          -- e.g. the published timetable this row came from
    data_source     public.data_source_t,
    CONSTRAINT chk_timetable_validity CHECK (valid_to IS NULL OR valid_to >= valid_from),
    -- two versions of the same departure may not be valid on overlapping dates
    CONSTRAINT excl_timetable_version_overlap
        EXCLUDE USING gist (route_id WITH =, day_type WITH =, departure_time WITH =,
                            daterange(valid_from, valid_to, '[]') WITH &&)
);

-- A road segment closed during a time window (detours, construction, events).
CREATE TABLE IF NOT EXISTS public.road_closures (
    closure_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_id       integer NOT NULL REFERENCES public.road_segments(road_id),
    valid_period  tsrange NOT NULL CHECK (NOT isempty(valid_period)),
    reason        text,
    data_source   public.data_source_t,
    CONSTRAINT excl_road_closure_overlap
        EXCLUDE USING gist (road_id WITH =, valid_period WITH &&)
);

-- All tunable rules in one place, so assumptions are visible and documented.
CREATE TABLE IF NOT EXISTS public.service_params (
    param_key    varchar(50) PRIMARY KEY,
    param_value  numeric NOT NULL,
    unit         varchar(20),
    description  text NOT NULL,
    data_source  public.data_source_t DEFAULT 'assumed'
);

